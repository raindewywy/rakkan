/**
 * Writes test/TEST_CASES.md: a table of every Jest test case with its result,
 * plus the Playwright UI test cases found in tests/.
 *
 * Usage: npm run test:table
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const JSON_OUT = path.join(ROOT, 'test-results', 'jest-results.json');

function runJest() {
  fs.mkdirSync(path.dirname(JSON_OUT), { recursive: true });
  const run = spawnSync('npx', ['jest', '--json', `--outputFile=${JSON_OUT}`, '--coverage=false', '--silent'], {
    cwd: ROOT,
    shell: true,
    encoding: 'utf8'
  });
  if (!fs.existsSync(JSON_OUT)) {
    throw new Error(`Jest did not write a result file.\n${run.stderr}`);
  }
  return JSON.parse(fs.readFileSync(JSON_OUT, 'utf8'));
}

function escapeCell(text) {
  return String(text).replace(/\|/g, '\\|');
}

function main() {
  const report = runJest();
  const rows = [];
  report.testResults
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .forEach((suite) => {
      const file = path.relative(ROOT, suite.name).split(path.sep).join('/');
      suite.assertionResults.forEach((test) => {
        rows.push({ type: 'Unit / route (Jest)', file, name: test.fullName, status: test.status === 'passed' ? 'Pass' : 'Fail' });
      });
    });

  const uiDir = path.join(ROOT, 'tests');
  if (fs.existsSync(uiDir)) {
    fs.readdirSync(uiDir)
      .filter((name) => name.endsWith('.spec.js'))
      .sort()
      .forEach((name) => {
        const code = fs.readFileSync(path.join(uiDir, name), 'utf8');
        for (const match of code.matchAll(/test\('([^']+)'/g)) {
          rows.push({ type: 'UI (Playwright)', file: `tests/${name}`, name: match[1], status: 'See Playwright report' });
        }
      });
  }

  const lines = [
    '# Test cases',
    '',
    `Generated by \`npm run test:table\` on ${new Date().toISOString().slice(0, 10)}. The test name states the expected result.`,
    '',
    '| No. | Type | File | Test case (expected result) | Result |',
    '| ---: | --- | --- | --- | --- |'
  ];
  rows.forEach((row, index) => {
    lines.push(`| ${index + 1} | ${row.type} | ${row.file} | ${escapeCell(row.name)} | ${row.status} |`);
  });
  const passed = rows.filter((row) => row.status === 'Pass').length;
  const jestTotal = rows.filter((row) => row.type.startsWith('Unit')).length;
  lines.push('', `Jest: ${passed} of ${jestTotal} passed. UI tests: ${rows.length - jestTotal}.`);

  fs.writeFileSync(path.join(ROOT, 'test', 'TEST_CASES.md'), `${lines.join('\n')}\n`);
  console.log(`Wrote test/TEST_CASES.md (${rows.length} test cases)`);
}

main();
